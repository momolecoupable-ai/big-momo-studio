-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  nickname text,
  category text,
  club text,
  photo_url text,
  slug text not null unique,
  bio text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.players enable row level security;
drop policy if exists "Public can read published players" on public.players;
create policy "Public can read published players" on public.players for select using (published = true);
drop policy if exists "Owner manages players" on public.players;
-- Replace the UUID below with the owner's Supabase Auth user ID. The server API
-- also checks ADMIN_EMAIL and keeps the service role key out of browser code.
create policy "Owner manages players" on public.players for all to authenticated
using (auth.uid() = '00000000-0000-0000-0000-000000000000'::uuid)
with check (auth.uid() = '00000000-0000-0000-0000-000000000000'::uuid);

grant select on public.players to anon, authenticated;
grant all on public.players to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('player-photos', 'player-photos', true, 8388608, array['image/jpeg','image/png','image/webp','image/avif'])
on conflict (id) do update set public = true, file_size_limit = 8388608,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/avif'];

drop policy if exists "Public can view player photos" on storage.objects;
create policy "Public can view player photos" on storage.objects for select using (bucket_id = 'player-photos');
